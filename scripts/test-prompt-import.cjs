const assert = require("node:assert/strict");
const path = require("node:path");
const esbuild = require("esbuild");

(async () => {
  const result = await esbuild.build({ stdin: { contents: 'export { importPromptsFromFile } from "./src/lib/backup"; export { PROMPT_STORAGE_KEYS } from "./src/lib/prompt-library";', resolveDir: path.resolve(__dirname, "..") }, bundle: true, write: false, platform: "node", format: "cjs" });
  const loaded = { exports: {} };
  new Function("module", "exports", "require", result.outputFiles[0].text)(loaded, loaded.exports, require);
  const { importPromptsFromFile, PROMPT_STORAGE_KEYS } = loaded.exports;
  const data = { settings: { apiKey: "unchanged" }, history: ["unchanged"] };
  global.chrome = { storage: { local: { get: async key => ({ [key]: structuredClone(data[key]) }), set: async values => Object.assign(data, structuredClone(values)) } } };
  const record = (number, id = `new-${number}`) => ({ id, title: `标题${number}`, content: `正文${number}`, category: "收藏", tags: [], provider: "chatgpt", model: "", format: "cnPrompt", createdAt: "2026-10-13" });
  const original = Array.from({ length: 5 }, (_, i) => record(i, `old-${i}`));
  const incoming = Array.from({ length: 15 }, (_, i) => record(i));
  const file = records => new File([JSON.stringify({ favorites: records, folders: [], customTabs: [] })], "backup.json");
  data[PROMPT_STORAGE_KEYS.favorites] = structuredClone(original);
  let imported = await importPromptsFromFile(file(incoming), "append");
  assert.equal(imported.favorites, 10);
  assert.equal(imported.skipped, 5);
  assert.equal(data[PROMPT_STORAGE_KEYS.favorites].length, 15);
  assert.deepEqual(data[PROMPT_STORAGE_KEYS.favorites].slice(0, 5), original);
  imported = await importPromptsFromFile(file(incoming), "append");
  assert.equal(imported.favorites, 0);
  assert.equal(imported.skipped, 15);
  data[PROMPT_STORAGE_KEYS.favorites] = structuredClone(original);
  imported = await importPromptsFromFile(file(incoming.map((_, i) => record(i + 20))), "append");
  assert.equal(imported.favorites, 15);
  assert.equal(data[PROMPT_STORAGE_KEYS.favorites].length, 20);
  data[PROMPT_STORAGE_KEYS.folders] = [{ id: "old-folder", name: "旧文件夹" }];
  await importPromptsFromFile(file(incoming), "replace");
  assert.equal(data[PROMPT_STORAGE_KEYS.favorites].length, 15);
  assert.deepEqual(new Set(data[PROMPT_STORAGE_KEYS.favorites].map(r => r.id)), new Set(incoming.map(r => r.id)));
  assert.deepEqual(data[PROMPT_STORAGE_KEYS.folders], []);
  const snapshot = structuredClone(data);
  await assert.rejects(importPromptsFromFile(new File(["bad JSON"], "bad.json"), "replace"));
  assert.deepEqual(data, snapshot);
  assert.deepEqual(data.settings, { apiKey: "unchanged" });
  assert.deepEqual(data.history, ["unchanged"]);
  console.log("PASS: append 10 of 15, append all 15, reimport deduplication, full replacement and invalid-file preservation");
})().catch(error => { console.error(error); process.exitCode = 1; });
