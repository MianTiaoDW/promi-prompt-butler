const assert = require('node:assert/strict');
const path = require('node:path');
const { build } = require('esbuild');
const { unzipSync, strFromU8 } = require('fflate');
(async () => {
  const bundle = await build({ stdin: { contents: 'export * from "./src/lib/prompt-library"; export * from "./src/lib/prompt-group"; export * from "./src/lib/backup";', resolveDir: path.resolve(__dirname, '..') }, bundle: true, write: false, platform: 'node', format: 'cjs' });
  const module = { exports: {} }; new Function('module', 'exports', 'require', bundle.outputFiles[0].text)(module, module.exports, require);
  const api = module.exports, data = {}; let zipped;
  global.chrome = { storage: { local: { get: async key => ({ [key]: structuredClone(data[key]) }), set: async values => Object.assign(data, structuredClone(values)) } }, downloads: { download: async ({ url }) => { zipped = new Uint8Array(await (await fetch(url)).arrayBuffer()); return 1; } } };
  const style = { kind: 'background', light: '#fff0a6', dark: '#584b1c', opacity: .45 };
  const marks = [{ ...style, start: 0, end: 2 }, { kind: "bold", light: "#000000", dark: "#ffffff", start: 0, end: 2 }];
  const record = await api.savePromptToFavorites({ provider: 'chatgpt', model: '', format: 'cnPrompt', title: '标记', content: '重点正文', marks, variantMarks: { cnPrompt: marks } });
  assert.deepEqual(record.marks, marks);
  let updated = await api.updateFavoritePrompt(record.id, { content: '新重点正文', contentVariants: { cnPrompt: '新重点正文' } });
  assert.deepEqual(updated.marks.map(mark => [mark.start, mark.end]), [[1, 3], [1, 3]], 'Content updates move offsets without changing text');
  assert.deepEqual(updated.variantMarks.cnPrompt, updated.marks);
  const group = { notes: '用途', steps: [{ name: '准备', content: '重点步骤', marks }, { name: '', content: '重点步骤', marks }] };
  const content = api.formatPromptGroup(group);
  updated = await api.updateFavoritePrompt(record.id, { group, content, marks: [] });
  const flattened = api.getPromptContentMarks(updated);
  assert.equal(flattened.length, 4);
  assert.deepEqual(flattened.map(mark => content.slice(mark.start, mark.end)), ['重点', '重点', '重点', '重点']);
  assert(flattened[2].start > flattened[0].end, 'Identical steps maintain their own positions');
  await api.exportPromptsAsZip();
  const backup = JSON.parse(strFromU8(unzipSync(zipped)['prompts.json']));
  assert.deepEqual(backup.favorites[0].group.steps[0].marks, marks);
  data[api.PROMPT_STORAGE_KEYS.favorites] = [];
  await api.importPromptsFromFile(new File([zipped], 'marked.zip'), 'replace');
  assert.deepEqual(data[api.PROMPT_STORAGE_KEYS.favorites][0].group, group, 'ZIP roundtrip retains step marks');
  assert.equal(data[api.PROMPT_STORAGE_KEYS.favorites][0].content, content, 'Backups keep plain text with no markup');
  console.log('PASS: marked record saves, edit remapping, flattened group handoff, ZIP export/import and plain content');
})().catch(error => { console.error(error); process.exitCode = 1; });
